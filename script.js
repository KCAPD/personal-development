let currentYear = 1;
let currentStrand = "integrity";

const tabs = document.querySelectorAll(".kca-year-button");
const strandTabs = document.querySelectorAll(".year-value-tab");

function renderStrand(strand) {
  currentStrand = strand;
  const data = years[currentYear].strands[strand];
  const meta = strandMeta[strand];

  document.getElementById("strandImage").src = meta.image;
  document.getElementById("strandImage").alt = meta.alt;
  document.getElementById("strandImage").style.animation = "none";
  void document.getElementById("strandImage").offsetWidth;
  document.getElementById("strandImage").style.animation = "";

  document.getElementById("strandLabel").textContent = meta.label;
  document.getElementById("strandTitle").textContent = data[0];
  document.getElementById("strandSummary").textContent = data[1];
  document.getElementById("strandOutcomes").innerHTML = data[2].map(item => `<li>${item}</li>`).join("");

  strandTabs.forEach(button => {
    const active = button.dataset.strand === strand;
    button.classList.toggle("active", active);
    button.setAttribute("aria-selected", String(active));
  });
}

function renderYear(number) {
  currentYear = number;
  const year = years[number];

  document.getElementById("yearKicker").textContent = year.kicker;
  document.getElementById("yearTitle").textContent = year.title;
  document.getElementById("yearIntro").textContent = year.intro;
  document.getElementById("yearCharacter").src = year.character;
  document.getElementById("yearCharacter").alt = year.characterName;
  document.getElementById("characterCaption").textContent = year.characterName;
  document.getElementById("speechBubble").textContent = year.quote;
  document.getElementById("reflectionTitle").textContent = `My Year ${number} reflection`;

  document.getElementById("experiences").innerHTML = year.experiences.map(item => `<span>${item}</span>`).join("");
  document.getElementById("reflectionPrompts").innerHTML = year.reflections.map(item => `<div class="reflection-prompt">${item}</div>`).join("");

  const progress = ((number - 1) / 5) * 100;
  document.getElementById("lineFill").style.width = `calc(${progress}% - ${progress === 0 ? 0 : 40}px)`;
  document.getElementById("movingTrain").style.left = `calc(30px + (100% - 100px) * ${(number - 1) / 5})`;

  tabs.forEach(tab => {
    const active = Number(tab.dataset.year) === number;
    tab.classList.toggle("active", active);
    tab.setAttribute("aria-selected", String(active));
  });

  renderStrand(currentStrand);
}

tabs.forEach(tab => {
  tab.addEventListener("click", () => renderYear(Number(tab.dataset.year)));
});

strandTabs.forEach(button => {
  button.addEventListener("click", () => renderStrand(button.dataset.strand));
});

document.getElementById("beginJourney").addEventListener("click", () => {
  document.getElementById("journey").scrollIntoView({ behavior: "smooth" });
});

