const dialog = document.getElementById("characterDialog");
const dialogClose = document.getElementById("dialogClose");

document.querySelectorAll(".value-card[data-value]").forEach(card => {
  card.addEventListener("click", () => {
    const story = valueStories[card.dataset.value];
    document.getElementById("dialogImage").src = story.image;
    document.getElementById("dialogImage").alt = story.title;
    document.getElementById("dialogTitle").textContent = story.title;
    document.getElementById("dialogStrand").textContent = story.strand;
    document.getElementById("dialogLead").textContent = story.lead;
    document.getElementById("dialogDetails").innerHTML = story.details.map(paragraph => `<p>${paragraph}</p>`).join("");
    document.getElementById("dialogAction").textContent = story.action;
    dialog.showModal();
    document.body.classList.add("dialog-open");
  });
});

function closeCharacterDialog() {
  dialog.close();
  document.body.classList.remove("dialog-open");
}

dialogClose.addEventListener("click", closeCharacterDialog);
dialog.addEventListener("click", event => {
  if (event.target === dialog) closeCharacterDialog();
});
dialog.addEventListener("close", () => document.body.classList.remove("dialog-open"));

